use super::{linux, prelude::*};

pub struct FreeBsd;

impl PlatformDetails for FreeBsd {
    fn uses_freetype(&self) -> bool {
        true
    }

    fn gn_args(&self, config: &BuildConfiguration, builder: &mut GnArgsBuilder) {
        // Skia's GN files only define `is_linux` (there is no `is_freebsd`) for Unix desktop
        // components such as `SkLog_stdio.cpp`, GLX, and `SK_R32_SHIFT=16`.
        // `builder.target_str` stays set to the FreeBSD target triple so clang compiles for FreeBSD.
        builder.target_os_and_default_cpu("linux");

        // FreeBSD's base `/usr/bin/ar` (elftoolchain) does not support `@file` response files
        // generated by Skia's GN/ninja rules; base FreeBSD ships `llvm-ar`, which does.
        builder.arg("ar", quote("llvm-ar"));

        // FreeBSD ports install headers (fontconfig, GL, etc.) under `/usr/local/include`.
        // Use `-idirafter` so `/usr/local/include` is searched after Skia's vendored
        // `-isystem` third-party headers (e.g. zlib/libpng) and never shadows them.
        builder.cflag("-idirafter/usr/local/include");

        // FreeBSD ports install FreeType headers under `/usr/local/include/freetype2`
        // rather than `/usr/include/freetype2`.
        if !config.features[feature::EMBED_FREETYPE] {
            builder.cflag("-I=/usr/local/include/freetype2");
            builder.cflag("-I/usr/local/include/freetype2");
        }
    }

    fn bindgen_args(&self, _target: &Target, builder: &mut BindgenArgsBuilder) {
        builder.arg("-idirafter/usr/local/include");
    }

    fn link_libraries(&self, features: &Features) -> Vec<String> {
        linux::link_libraries_with_cpp_stdlib(features, "c++")
    }
}
